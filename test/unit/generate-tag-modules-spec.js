import {expect} from 'chai';
import fs from 'fs';
import os from 'os';
import path from 'path';
import {fileURLToPath, pathToFileURL} from 'url';
import {generateTagModules, writeTagModules} from '../../bin/generate-tag-modules.js';
import {swapProperties} from './test-utils.js';
import {getTagBindingName} from '../../src/composable/tag-binding-name.js';
import TagNames0thIfd from '../../src/tag-names-0th-ifd.js';
import TagNamesExifIfd from '../../src/tag-names-exif-ifd.js';
import TagNamesGpsIfd from '../../src/tag-names-gps-ifd.js';
import TagNamesInteroperabilityIfd from '../../src/tag-names-interoperability-ifd.js';
import TagNamesMpfIfd from '../../src/tag-names-mpf-ifd.js';
import IptcTagNames from '../../src/iptc-tag-names.js';
import TagNamesCommon from '../../src/tag-names-common.js';
import {getVersionString} from '../../src/tag-names-utils.js';
import {getRecord2DestinationDescription} from '../../src/iptc-tag-names-descriptions.js';
import {exifBlockReader} from '../../src/composable/exif-block-reader.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const EXIF_PATH = 'src/composable/tags/exif.js';
const IPTC_PATH = 'src/composable/tags/iptc.js';
const MPF_PATH = 'src/composable/tags/mpf.js';
const EXIF_TYPES_PATH = 'src/composable/tags/exif.d.ts';
const IPTC_TYPES_PATH = 'src/composable/tags/iptc.d.ts';
const MPF_TYPES_PATH = 'src/composable/tags/mpf.d.ts';
const GENERATED_LINE = '// Generated by bin/generate-tag-modules.js from the tag dictionaries; do not edit.';
const DUAL_NAME_COMMENT = '// One id, two names: the dictionary names this tag by the length of its value.';
const TYPES_IMPORT = 'import type {TagDescriptor} from \'../core.js\';';
const READER_IMPORT = 'import {exifBlockReader} from \'../exif-block-reader.js\';';
const OUTPUT_FILES = [
    {
        path: EXIF_PATH,
        typesPath: EXIF_TYPES_PATH,
        group: 'exif',
        dictionaries: [
            ['0th', TagNames0thIfd],
            ['exif', TagNamesExifIfd],
            ['gps', TagNamesGpsIfd],
            ['interoperability', TagNamesInteroperabilityIfd]
        ]
    },
    {path: IPTC_PATH, typesPath: IPTC_TYPES_PATH, group: 'iptc', dictionaries: [['iptc', IptcTagNames.iptc]]},
    {path: MPF_PATH, typesPath: MPF_TYPES_PATH, group: 'mpf', dictionaries: [['mpf', TagNamesMpfIfd]]}
];
const UNUSED_EXIF_ID = 0xfff0;

describe('generate-tag-modules', () => {
    const restores = [];

    afterEach(() => {
        while (restores.length > 0) {
            restores.pop()();
        }
    });

    describe('generateTagModules', () => {
        it('should return the three tag modules and their type definitions, in order', () => {
            expect(Object.keys(generateTagModules())).to.deep.equal([
                EXIF_PATH,
                EXIF_TYPES_PATH,
                IPTC_PATH,
                IPTC_TYPES_PATH,
                MPF_PATH,
                MPF_TYPES_PATH
            ]);
        });

        it('should list every output in package.json exports and typesVersions, and nothing else under tags', () => {
            const packageJson = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
            const paths = Object.keys(generateTagModules());
            const expectedExports = {};
            const expectedTypesVersions = {};
            for (let i = 0; i < paths.length; i += 2) {
                const name = path.basename(paths[i], '.js');
                expectedExports['./tags/' + name] = {types: './' + paths[i + 1], default: './' + paths[i]};
                expectedTypesVersions['tags/' + name] = ['./' + paths[i + 1]];
            }
            const tagExports = Object.fromEntries(Object.entries(packageJson.exports).filter(([key]) => key.startsWith('./tags/')));
            const tagTypesVersions = Object.fromEntries(Object.entries(packageJson.typesVersions['*']).filter(([key]) => key.startsWith('tags/')));

            expect(tagExports).to.deep.equal(expectedExports);
            for (const key of Object.keys(tagExports)) {
                expect(Object.keys(tagExports[key]), key).to.deep.equal(['types', 'default']);
            }
            expect(tagTypesVersions).to.deep.equal(expectedTypesVersions);
        });

        it('should return what is committed', () => {
            const modules = generateTagModules();
            for (const relativePath of Object.keys(modules)) {
                const committed = readCommittedText(relativePath);
                expect(committed === modules[relativePath], `${relativePath} is stale: run npm run generate:tags`).to.equal(true);
            }
        });

        it('should start every file with the license header and the generated line', () => {
            const header = readCommittedText('src/tags.js').split('\n').slice(0, 3).join('\n');
            const modules = generateTagModules();
            for (const relativePath of Object.keys(modules)) {
                expect(modules[relativePath].startsWith(header + '\n\n' + GENERATED_LINE + '\n\n'), relativePath).to.equal(true);
            }
        });

        it('should import TagDescriptor type-only in every type definition', () => {
            const modules = generateTagModules();
            for (const output of OUTPUT_FILES) {
                expect(modules[output.typesPath], output.typesPath).to.include('\n\n' + TYPES_IMPORT + '\n\n');
            }
        });

        it('should declare every export of its module, in its order, as a TagDescriptor of its group and output name', async () => {
            const modules = generateTagModules();
            for (const output of OUTPUT_FILES) {
                const moduleBindings = getMatches(modules[output.path], /^export const (\w+) = /gm);
                const typesText = modules[output.typesPath];
                const declarations = [...typesText.matchAll(new RegExp(`^export declare const (\\w+): TagDescriptor<'${output.group}', '((?:[^'\\\\]|\\\\.)*)'>;$`, 'gm'))];
                const declaredBindings = declarations.map((match) => match[1]);
                const linesAfterImport = typesText.split(TYPES_IMPORT + '\n')[1].split('\n').filter((line) => line !== '');
                const module = await importGenerated(output.path);

                expect(declaredBindings, output.typesPath).to.deep.equal(moduleBindings);
                expect([...declaredBindings].sort(), output.typesPath).to.deep.equal(Object.keys(module).sort());
                expect(linesAfterImport.length, output.typesPath).to.equal(declaredBindings.length);
                for (const [, binding, quotedName] of declarations) {
                    expect(getUnescapedStringLiteral(quotedName), `${output.typesPath} ${binding}`).to.equal(module[binding].name);
                }
            }
        });

        it('should write a type definition with one declaration per tag', () => {
            const header = readCommittedText('src/tags.js').split('\n').slice(0, 3);

            expect(generateTagModules()[MPF_TYPES_PATH]).to.equal([
                ...header,
                '',
                GENERATED_LINE,
                '',
                TYPES_IMPORT,
                '',
                'export declare const MPFVersion: TagDescriptor<\'mpf\', \'MPFVersion\'>;',
                'export declare const NumberOfImages: TagDescriptor<\'mpf\', \'NumberOfImages\'>;',
                'export declare const MPEntry: TagDescriptor<\'mpf\', \'MPEntry\'>;',
                'export declare const ImageUIDList: TagDescriptor<\'mpf\', \'ImageUIDList\'>;',
                'export declare const TotalFrames: TagDescriptor<\'mpf\', \'TotalFrames\'>;',
                ''
            ].join('\n'));
        });

        it('should export one descriptor per sanitized dictionary name', async () => {
            for (const output of OUTPUT_FILES) {
                const module = await importGenerated(output.path);
                const bindings = getOutputNames(output).map(getTagBindingName);
                expect(Object.keys(module).sort(), output.path).to.deep.equal(bindings.sort());
            }
        });

        it('should give every descriptor the name, ids, group, dictionary and description of its entries, and only those fields', async () => {
            for (const output of OUTPUT_FILES) {
                const module = await importGenerated(output.path);
                const describedBindings = new Set();
                const describedIds = new Map();
                for (const [dictionaryKey, dictionary] of output.dictionaries) {
                    for (const key of Object.keys(dictionary)) {
                        const entry = dictionary[key];
                        for (const name of getEntryNames(entry)) {
                            const descriptor = module[getTagBindingName(name)];
                            const label = `${output.path} ${key} ${name}`;
                            expect(descriptor.name, label).to.equal(name);
                            expect(descriptor.ids, label).to.include(Number(key));
                            expect(descriptor.group, label).to.equal(output.group);
                            expect(descriptor.dictionary, label).to.equal(dictionaryKey);
                            if (entry.description) {
                                expect(descriptor.description === entry.description, label).to.equal(true);
                                describedBindings.add(getTagBindingName(name));
                                describedIds.set(getTagBindingName(name), (describedIds.get(getTagBindingName(name)) || []).concat([Number(key)]));
                            }
                        }
                    }
                }
                for (const binding of Object.keys(module)) {
                    const descriptor = module[binding];
                    const isDescribed = describedBindings.has(binding);
                    const isPartlyDescribed = isDescribed && describedIds.get(binding).length < descriptor.ids.length;
                    const fields = ['name', 'ids', 'group', 'dictionary']
                        .concat(isDescribed ? ['description'] : [], isPartlyDescribed ? ['describedIds'] : [], output.group === 'exif' ? ['reader'] : []);
                    expect(Object.keys(descriptor), binding).to.deep.equal(fields);
                    if (isPartlyDescribed) {
                        expect(descriptor.describedIds, binding).to.deep.equal(describedIds.get(binding));
                    }
                    if (output.group === 'exif') {
                        expect(descriptor.reader, binding).to.equal(exifBlockReader);
                    }
                }
            }
        });

        it('should link every exif descriptor to the Exif block reader, and no iptc or mpf one', () => {
            const modules = generateTagModules();
            const exifText = modules[EXIF_PATH];
            const descriptorLines = exifText.split('\n').filter((line) => line.startsWith('export const '));

            expect(exifText).to.include('\n' + READER_IMPORT + '\n\n');
            expect(exifText.split(READER_IMPORT)[0]).to.match(/from '\.\.\/\.\.\/tag-names-common\.js';\n$/);
            expect(descriptorLines.length).to.be.above(0);
            for (const line of descriptorLines) {
                expect(line.endsWith(', reader: exifBlockReader};'), line).to.equal(true);
            }
            for (const relativePath of [IPTC_PATH, MPF_PATH]) {
                expect(modules[relativePath], relativePath).to.not.include('exifBlockReader');
                expect(modules[relativePath], relativePath).to.not.include('exif-block-reader');
            }
        });

        it('should mark the described ids of a descriptor whose ids are not all described', async () => {
            const module = await importGenerated(EXIF_PATH);
            const marked = Object.keys(module).filter((binding) => 'describedIds' in module[binding]);

            expect(marked.sort()).to.deep.equal(['Contrast', 'Saturation', 'Sharpness', 'WhiteBalance']);
            expect(module.WhiteBalance.describedIds).to.deep.equal([0xa403]);
            expect(module.Contrast.describedIds).to.deep.equal([0xa408]);
            expect(module.Saturation.describedIds).to.deep.equal([0xa409]);
            expect(module.Sharpness.describedIds).to.deep.equal([0xa40a]);
            expect(generateTagModules()[EXIF_PATH]).to.include('description: getWhiteBalanceDescription, describedIds: [0xa403], reader: exifBlockReader};');
        });

        it('should give a name with two ids both, with the description of the described one', async () => {
            const module = await importGenerated(EXIF_PATH);
            const multipleIds = Object.keys(module).filter((binding) => module[binding].ids.length > 1);

            expect(multipleIds.sort()).to.deep.equal(['Contrast', 'Saturation', 'Sharpness', 'WhiteBalance']);
            expect(module.WhiteBalance.ids).to.deep.equal([0xa403, 0xfe4e]);
            expect(module.Contrast.ids).to.deep.equal([0xa408, 0xfe54]);
            expect(module.Saturation.ids).to.deep.equal([0xa409, 0xfe55]);
            expect(module.Sharpness.ids).to.deep.equal([0xa40a, 0xfe56]);
            for (const binding of multipleIds) {
                const description = TagNamesExifIfd[module[binding].ids[0]].description;
                expect(description, binding).to.be.a('function');
                expect(module[binding].description === description, binding).to.equal(true);
            }
        });

        it('should give each name of IPTC 0x02c8 its own descriptor', async () => {
            const module = await importGenerated(IPTC_PATH);

            expect(module.ObjectDataPreviewFileFormat).to.deep.equal({
                name: 'ObjectData Preview File Format',
                ids: [0x02c8],
                group: 'iptc',
                dictionary: 'iptc',
                description: getRecord2DestinationDescription
            });
            expect(module.Record2Destination).to.deep.equal({
                name: 'Record 2 destination',
                ids: [0x02c8],
                group: 'iptc',
                dictionary: 'iptc',
                description: getRecord2DestinationDescription
            });
            expect(generateTagModules()[IPTC_PATH]).to.include(DUAL_NAME_COMMENT + '\nexport const ObjectDataPreviewFileFormat = ');
        });

        it('should write no default import and no reference to the tag-names-common.js default object', () => {
            const modules = generateTagModules();

            for (const relativePath of [EXIF_PATH, IPTC_PATH, MPF_PATH]) {
                expect(modules[relativePath], relativePath).to.not.match(/^import \w+[ ,]/m);
            }
            expect(modules[EXIF_PATH]).to.not.include('TagNamesCommon');
        });

        it('should write a single import on one line and several one per line', () => {
            const modules = generateTagModules();

            expect(modules[MPF_PATH]).to.include('\nimport {getVersionString} from \'../../tag-names-utils.js\';\n');
            expect(modules[EXIF_PATH]).to.match(/\nimport {\n {4}\w+,\n {4}\w+,\n/);
        });

        it('should write no import block for a module without descriptions', () => {
            restores.push(swapProperties(TagNamesMpfIfd, {0xb000: 'MPFVersion'}));

            expect(generateTagModules()[MPF_PATH]).to.include(GENERATED_LINE + '\n\nexport const MPFVersion = {name: \'MPFVersion\', ids: [0xb000], group: \'mpf\', dictionary: \'mpf\'};\n');
        });

        it('should take the description of a later id when the first has none', () => {
            restores.push(swapProperties(TagNamesExifIfd, {
                0xa403: 'WhiteBalance',
                0xfe4e: {name: 'WhiteBalance', description: TagNamesCommon.WhiteBalance}
            }));

            expect(generateTagModules()[EXIF_PATH]).to.include('export const WhiteBalance = {name: \'WhiteBalance\', ids: [0xa403, 0xfe4e], group: \'exif\', dictionary: \'exif\', description: getWhiteBalanceDescription, describedIds: [0xfe4e], reader: exifBlockReader};\n');
        });

        it('should quote a name with a quote or a backslash', () => {
            restores.push(swapProperties(TagNamesExifIfd, {[UNUSED_EXIF_ID]: 'Odd\'Name\\'}));

            expect(generateTagModules()[EXIF_PATH]).to.include('export const OddName = {name: \'Odd\\\'Name\\\\\', ids: [0xfff0], group: \'exif\', dictionary: \'exif\', reader: exifBlockReader};\n');
        });

        it('should throw for a description that no description module exports', () => {
            restores.push(swapProperties(TagNamesGpsIfd, {0x0001: {name: 'GPSLatitudeRef', description: (value) => value}}));

            expect(() => generateTagModules()).to.throw(/GPSLatitudeRef.*has no export in the description modules/);
        });

        it('should throw for a name whose ids carry two descriptions', () => {
            restores.push(swapProperties(TagNamesExifIfd, {0xfe4e: {name: 'WhiteBalance', description: getVersionString}}));

            expect(() => generateTagModules()).to.throw(/WhiteBalance.*has two different descriptions/);
        });

        it('should throw for a name in two dictionaries of one module', () => {
            restores.push(swapProperties(TagNamesGpsIfd, {0x0001: 'DateTime'}));

            expect(() => generateTagModules()).to.throw(/DateTime.*is in two dictionaries/);
        });

        it('should throw for a name declared twice in one module', () => {
            restores.push(swapProperties(TagNamesExifIfd, {[UNUSED_EXIF_ID]: 'Exif-IFD-Pointer'}));

            expect(() => generateTagModules()).to.throw(/ExifIFDPointer is declared twice in src\/composable\/tags\/exif\.js/);
        });

        it('should bind a tag named as the reader import under a capitalized name, apart from the import', () => {
            restores.push(swapProperties(TagNamesExifIfd, {[UNUSED_EXIF_ID]: 'exifBlockReader'}));

            expect(generateTagModules()[EXIF_PATH]).to.include('export const ExifBlockReader = {name: \'exifBlockReader\', ids: [0xfff0], group: \'exif\', dictionary: \'exif\', reader: exifBlockReader};\n');
        });
    });

    describe('writeTagModules', () => {
        let root;

        beforeEach(() => {
            root = fs.mkdtempSync(path.join(os.tmpdir(), 'exifreader-generate-tags-'));
        });

        afterEach(() => {
            fs.rmSync(root, {recursive: true, force: true});
        });

        it('should write every generated module under the root', () => {
            writeTagModules(root);

            const modules = generateTagModules();
            for (const relativePath of Object.keys(modules)) {
                expect(fs.readFileSync(path.join(root, relativePath), 'utf8'), relativePath).to.equal(modules[relativePath]);
            }
        });
    });
});

// A Windows checkout can have CRLF line endings, and the generator writes LF.
function readCommittedText(relativePath) {
    return fs.readFileSync(path.join(ROOT, relativePath), 'utf8').replace(/\r\n/g, '\n');
}

// Imported per test, so a stale module fails only the tests that load it.
function importGenerated(relativePath) {
    return import(pathToFileURL(path.join(ROOT, relativePath)).href);
}

function getMatches(text, pattern) {
    return [...text.matchAll(pattern)].map((match) => match[1]);
}

function getUnescapedStringLiteral(text) {
    return text.replace(/\\(.)/g, '$1');
}

function getOutputNames(output) {
    const names = new Set();
    for (const [, dictionary] of output.dictionaries) {
        for (const key of Object.keys(dictionary)) {
            for (const name of getEntryNames(dictionary[key])) {
                names.add(name);
            }
        }
    }
    return [...names];
}

function getEntryNames(entry) {
    if (typeof entry === 'string') {
        return [entry];
    }
    if (typeof entry.name === 'function') {
        return [entry.name([0, 0]), entry.name([0])];
    }
    return [entry.name];
}
