import {expect} from 'chai';
import fs from 'fs';
import os from 'os';
import path from 'path';
import {fileURLToPath, pathToFileURL} from 'url';
import {generateTagModules, writeTagModules} from '../../bin/generate-tag-modules.js';
import {swapProperties} from './test-utils.js';
import {getTagBindingName} from '../../src/composable/tag-binding-name.js';
import TagNames0thIfd from '../../src/tag-names-0th-ifd.js';
import TagNamesExifIfd from '../../src/tag-names-exif-ifd.js';
import TagNamesGpsIfd from '../../src/tag-names-gps-ifd.js';
import TagNamesInteroperabilityIfd from '../../src/tag-names-interoperability-ifd.js';
import TagNamesMpfIfd from '../../src/tag-names-mpf-ifd.js';
import IptcTagNames from '../../src/iptc-tag-names.js';
import TagNamesCommon from '../../src/tag-names-common.js';
import {getVersionString} from '../../src/tag-names-utils.js';
import {getRecord2DestinationDescription} from '../../src/iptc-tag-names-descriptions.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const EXIF_PATH = 'src/composable/tags/exif.js';
const IPTC_PATH = 'src/composable/tags/iptc.js';
const MPF_PATH = 'src/composable/tags/mpf.js';
const GENERATED_LINE = '// Generated by bin/generate-tag-modules.js from the tag dictionaries; do not edit.';
const DUAL_NAME_COMMENT = '// One id, two names: the dictionary names this tag by the length of its value.';
const OUTPUT_FILES = [
    {
        path: EXIF_PATH,
        group: 'exif',
        dictionaries: [
            ['0th', TagNames0thIfd],
            ['exif', TagNamesExifIfd],
            ['gps', TagNamesGpsIfd],
            ['interoperability', TagNamesInteroperabilityIfd]
        ]
    },
    {path: IPTC_PATH, group: 'iptc', dictionaries: [['iptc', IptcTagNames.iptc]]},
    {path: MPF_PATH, group: 'mpf', dictionaries: [['mpf', TagNamesMpfIfd]]}
];
const UNUSED_EXIF_ID = 0xfff0;

describe('generate-tag-modules', () => {
    const restores = [];

    afterEach(() => {
        while (restores.length > 0) {
            restores.pop()();
        }
    });

    describe('generateTagModules', () => {
        it('should return the three tag modules, in order', () => {
            expect(Object.keys(generateTagModules())).to.deep.equal([EXIF_PATH, IPTC_PATH, MPF_PATH]);
        });

        it('should return what is committed', () => {
            const modules = generateTagModules();
            for (const relativePath of Object.keys(modules)) {
                const committed = readCommittedText(relativePath);
                expect(committed === modules[relativePath], `${relativePath} is stale: run npm run generate:tags`).to.equal(true);
            }
        });

        it('should start every module with the license header and the generated line', () => {
            const header = readCommittedText('src/tags.js').split('\n').slice(0, 3).join('\n');
            const modules = generateTagModules();
            for (const relativePath of Object.keys(modules)) {
                expect(modules[relativePath].startsWith(header + '\n\n' + GENERATED_LINE + '\n\n'), relativePath).to.equal(true);
            }
        });

        it('should export one descriptor per sanitized dictionary name', async () => {
            for (const output of OUTPUT_FILES) {
                const module = await importGenerated(output.path);
                const bindings = getOutputNames(output).map(getTagBindingName);
                expect(Object.keys(module).sort(), output.path).to.deep.equal(bindings.sort());
            }
        });

        it('should give every descriptor the name, ids, group, dictionary and description of its entries', async () => {
            for (const output of OUTPUT_FILES) {
                const module = await importGenerated(output.path);
                const describedBindings = new Set();
                for (const [dictionaryKey, dictionary] of output.dictionaries) {
                    for (const key of Object.keys(dictionary)) {
                        const entry = dictionary[key];
                        for (const name of getEntryNames(entry)) {
                            const descriptor = module[getTagBindingName(name)];
                            const label = `${output.path} ${key} ${name}`;
                            expect(descriptor.name, label).to.equal(name);
                            expect(descriptor.ids, label).to.include(Number(key));
                            expect(descriptor.group, label).to.equal(output.group);
                            expect(descriptor.dictionary, label).to.equal(dictionaryKey);
                            if (entry.description) {
                                expect(descriptor.description === entry.description, label).to.equal(true);
                                describedBindings.add(getTagBindingName(name));
                            }
                        }
                    }
                }
                for (const binding of Object.keys(module)) {
                    expect('description' in module[binding], binding).to.equal(describedBindings.has(binding));
                }
            }
        });

        it('should give a name with two ids both, with the description of the described one', async () => {
            const module = await importGenerated(EXIF_PATH);
            const multipleIds = Object.keys(module).filter((binding) => module[binding].ids.length > 1);

            expect(multipleIds.sort()).to.deep.equal(['Contrast', 'Saturation', 'Sharpness', 'WhiteBalance']);
            expect(module.WhiteBalance.ids).to.deep.equal([0xa403, 0xfe4e]);
            expect(module.Contrast.ids).to.deep.equal([0xa408, 0xfe54]);
            expect(module.Saturation.ids).to.deep.equal([0xa409, 0xfe55]);
            expect(module.Sharpness.ids).to.deep.equal([0xa40a, 0xfe56]);
            for (const binding of multipleIds) {
                const description = TagNamesExifIfd[module[binding].ids[0]].description;
                expect(description, binding).to.be.a('function');
                expect(module[binding].description === description, binding).to.equal(true);
            }
        });

        it('should give each name of IPTC 0x02c8 its own descriptor', async () => {
            const module = await importGenerated(IPTC_PATH);

            expect(module.ObjectDataPreviewFileFormat).to.deep.equal({
                name: 'ObjectData Preview File Format',
                ids: [0x02c8],
                group: 'iptc',
                dictionary: 'iptc',
                description: getRecord2DestinationDescription
            });
            expect(module.Record2Destination).to.deep.equal({
                name: 'Record 2 destination',
                ids: [0x02c8],
                group: 'iptc',
                dictionary: 'iptc',
                description: getRecord2DestinationDescription
            });
            expect(generateTagModules()[IPTC_PATH]).to.include(DUAL_NAME_COMMENT + '\nexport const ObjectDataPreviewFileFormat = ');
        });

        it('should reference a description object member through the object and alias an import named as a tag', async () => {
            const module = await importGenerated(EXIF_PATH);
            const text = generateTagModules()[EXIF_PATH];

            expect(module.XResolution.description === TagNamesCommon.XResolution).to.equal(true);
            expect(text).to.include('import TagNamesCommon, {FocalLengthIn35mmFilm as FocalLengthIn35mmFilmDescription} from \'../../tag-names-common.js\';');
            expect(text).to.include('description: TagNamesCommon.XResolution};');
            expect(text).to.include('description: FocalLengthIn35mmFilmDescription};');
        });

        it('should write a single import on one line and several one per line', () => {
            const modules = generateTagModules();

            expect(modules[MPF_PATH]).to.include('\nimport {getVersionString} from \'../../tag-names-utils.js\';\n');
            expect(modules[EXIF_PATH]).to.match(/\nimport {\n {4}\w+,\n {4}\w+,\n/);
        });

        it('should write no import block for a module without descriptions', () => {
            restores.push(swapProperties(TagNamesMpfIfd, {0xb000: 'MPFVersion'}));

            expect(generateTagModules()[MPF_PATH]).to.include(GENERATED_LINE + '\n\nexport const MPFVersion = {name: \'MPFVersion\', ids: [0xb000], group: \'mpf\', dictionary: \'mpf\'};\n');
        });

        it('should take the description of a later id when the first has none', () => {
            restores.push(swapProperties(TagNamesExifIfd, {
                0xa403: 'WhiteBalance',
                0xfe4e: {name: 'WhiteBalance', description: TagNamesCommon.WhiteBalance}
            }));

            expect(generateTagModules()[EXIF_PATH]).to.include('export const WhiteBalance = {name: \'WhiteBalance\', ids: [0xa403, 0xfe4e], group: \'exif\', dictionary: \'exif\', description: TagNamesCommon.WhiteBalance};\n');
        });

        it('should quote a name with a quote or a backslash', () => {
            restores.push(swapProperties(TagNamesExifIfd, {[UNUSED_EXIF_ID]: 'Odd\'Name\\'}));

            expect(generateTagModules()[EXIF_PATH]).to.include('export const OddName = {name: \'Odd\\\'Name\\\\\', ids: [0xfff0], group: \'exif\', dictionary: \'exif\'};\n');
        });

        it('should throw for a description that no description module exports', () => {
            restores.push(swapProperties(TagNamesGpsIfd, {0x0001: {name: 'GPSLatitudeRef', description: (value) => value}}));

            expect(() => generateTagModules()).to.throw(/GPSLatitudeRef.*has no export in the description modules/);
        });

        it('should throw for a name whose ids carry two descriptions', () => {
            restores.push(swapProperties(TagNamesExifIfd, {0xfe4e: {name: 'WhiteBalance', description: getVersionString}}));

            expect(() => generateTagModules()).to.throw(/WhiteBalance.*has two different descriptions/);
        });

        it('should throw for a name in two dictionaries of one module', () => {
            restores.push(swapProperties(TagNamesGpsIfd, {0x0001: 'DateTime'}));

            expect(() => generateTagModules()).to.throw(/DateTime.*is in two dictionaries/);
        });

        it('should throw for a name declared twice in one module', () => {
            restores.push(swapProperties(TagNamesExifIfd, {[UNUSED_EXIF_ID]: 'FocalLengthIn35mmFilmDescription'}));

            expect(() => generateTagModules()).to.throw(/FocalLengthIn35mmFilmDescription is declared twice in src\/composable\/tags\/exif\.js/);
        });

        it('should throw for a tag named as the default import', () => {
            restores.push(swapProperties(TagNamesExifIfd, {[UNUSED_EXIF_ID]: 'TagNamesCommon'}));

            expect(() => generateTagModules()).to.throw(/TagNamesCommon is declared twice in src\/composable\/tags\/exif\.js/);
        });
    });

    describe('writeTagModules', () => {
        let root;

        beforeEach(() => {
            root = fs.mkdtempSync(path.join(os.tmpdir(), 'exifreader-generate-tags-'));
        });

        afterEach(() => {
            fs.rmSync(root, {recursive: true, force: true});
        });

        it('should write every generated module under the root', () => {
            writeTagModules(root);

            const modules = generateTagModules();
            for (const relativePath of Object.keys(modules)) {
                expect(fs.readFileSync(path.join(root, relativePath), 'utf8'), relativePath).to.equal(modules[relativePath]);
            }
        });
    });
});

// A Windows checkout can have CRLF line endings, and the generator writes LF.
function readCommittedText(relativePath) {
    return fs.readFileSync(path.join(ROOT, relativePath), 'utf8').replace(/\r\n/g, '\n');
}

// Imported per test, so a stale module fails only the tests that load it.
function importGenerated(relativePath) {
    return import(pathToFileURL(path.join(ROOT, relativePath)).href);
}

function getOutputNames(output) {
    const names = new Set();
    for (const [, dictionary] of output.dictionaries) {
        for (const key of Object.keys(dictionary)) {
            for (const name of getEntryNames(dictionary[key])) {
                names.add(name);
            }
        }
    }
    return [...names];
}

function getEntryNames(entry) {
    if (typeof entry === 'string') {
        return [entry];
    }
    if (typeof entry.name === 'function') {
        return [entry.name([0, 0]), entry.name([0])];
    }
    return [entry.name];
}
