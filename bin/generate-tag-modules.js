const fs = require('fs');
const path = require('path');
const {getTagBindingName} = require('../src/composable/tag-binding-name.js');
const TagNames0thIfd = require('../src/tag-names-0th-ifd.js');
const TagNamesExifIfd = require('../src/tag-names-exif-ifd.js');
const TagNamesGpsIfd = require('../src/tag-names-gps-ifd.js');
const TagNamesInteroperabilityIfd = require('../src/tag-names-interoperability-ifd.js');
const IptcTagNames = require('../src/iptc-tag-names.js');
const TagNamesMpfIfd = require('../src/tag-names-mpf-ifd.js');

const MPL_HEADER = [
    '/* This Source Code Form is subject to the terms of the Mozilla Public',
    ' * License, v. 2.0. If a copy of the MPL was not distributed with this',
    ' * file, You can obtain one at https://mozilla.org/MPL/2.0/. */'
];
const GENERATED_LINE = '// Generated by bin/generate-tag-modules.js from the tag dictionaries; do not edit.';
const DUAL_NAME_COMMENT = '// One id, two names: the dictionary names this tag by the length of its value.';
const TYPES_IMPORT = 'import type {TagDescriptor} from \'../core.js\';';
const COMMON_FILE = 'tag-names-common.js';
// In the order the imports are written and a function is looked up.
const DESCRIPTION_FILES = [
    'tag-names-0th-ifd-descriptions.js',
    'tag-names-exif-ifd-descriptions.js',
    'tag-names-gps-ifd-descriptions.js',
    'iptc-tag-names-descriptions.js',
    'tag-names-utils.js',
    COMMON_FILE
];
const DESCRIPTION_MODULES = DESCRIPTION_FILES.map((file) => require('../src/' + file));

module.exports = {generateTagModules, writeTagModules};

if (require.main === module) {
    writeTagModules(path.join(__dirname, '..'));
}

/**
 * Writes the generated modules under the given repository root.
 *
 * @param {string} root
 */
function writeTagModules(root) {
    const modules = generateTagModules();
    for (const relativePath of Object.keys(modules)) {
        const filePath = path.join(root, relativePath);
        fs.mkdirSync(path.dirname(filePath), {recursive: true});
        fs.writeFileSync(filePath, modules[relativePath]);
    }
}

/**
 * The text of every per-tag module and its type definitions, keyed by its
 * path from the repository root.
 *
 * @returns {Object<string, string>}
 * @throws {Error} When a dictionary entry cannot be described by an import or
 *     a name cannot be given a single descriptor.
 */
function generateTagModules() {
    const descriptionExports = getDescriptionExports();
    const modules = {};
    for (const output of getOutputs()) {
        const descriptors = getDescriptors(output);
        modules[output.path] = getModuleText(output, descriptors, descriptionExports);
        modules[output.typesPath] = getTypesText(descriptors, output.group);
    }
    return modules;
}

function getDescriptionExports() {
    const descriptionExports = new Map();
    DESCRIPTION_FILES.forEach((file, index) => {
        const namespace = DESCRIPTION_MODULES[index];
        for (const importName of Object.keys(namespace)) {
            const value = namespace[importName];
            if (importName !== 'default' && typeof value === 'function' && !descriptionExports.has(value)) {
                descriptionExports.set(value, {file, importName});
            }
        }
    });
    return descriptionExports;
}

function getOutputs() {
    return [
        {
            path: 'src/composable/tags/exif.js',
            typesPath: 'src/composable/tags/exif.d.ts',
            group: 'exif',
            dictionaries: [
                ['0th', TagNames0thIfd.default],
                ['exif', TagNamesExifIfd.default],
                ['gps', TagNamesGpsIfd.default],
                ['interoperability', TagNamesInteroperabilityIfd.default]
            ],
            reader: {binding: 'exifBlockReader', file: '../exif-block-reader.js'}
        },
        {
            path: 'src/composable/tags/iptc.js',
            typesPath: 'src/composable/tags/iptc.d.ts',
            group: 'iptc',
            dictionaries: [['iptc', IptcTagNames.default.iptc]]
        },
        {
            path: 'src/composable/tags/mpf.js',
            typesPath: 'src/composable/tags/mpf.d.ts',
            group: 'mpf',
            dictionaries: [['mpf', TagNamesMpfIfd.default]]
        }
    ];
}

// In dictionary order, then by first id. A name seen again joins the
// descriptor it first appeared in.
function getDescriptors(output) {
    const descriptors = [];
    const descriptorsByName = new Map();
    for (const [dictionary, entries] of output.dictionaries) {
        for (const key of Object.keys(entries)) {
            const id = Number(key);
            const entry = entries[key];
            const names = getEntryNames(entry);
            names.forEach((name, index) => {
                const description = typeof entry === 'string' ? undefined : entry.description;
                const descriptor = descriptorsByName.get(name);
                if (descriptor) {
                    addId(descriptor, id, dictionary, description);
                } else {
                    const newDescriptor = {
                        name,
                        binding: getTagBindingName(name),
                        ids: [id],
                        dictionary,
                        description,
                        describedIds: description ? [id] : [],
                        isFirstOfDualName: names.length > 1 && index === 0
                    };
                    descriptors.push(newDescriptor);
                    descriptorsByName.set(name, newDescriptor);
                }
            });
        }
    }
    return descriptors;
}

// A function-valued name gives both names it returns, for a two-element value
// and for any other, as bin/TagFilterPlugin.js resolves it.
function getEntryNames(entry) {
    if (typeof entry === 'string') {
        return [entry];
    }
    if (typeof entry.name === 'function') {
        return [entry.name([0, 0]), entry.name([0])];
    }
    return [entry.name];
}

function addId(descriptor, id, dictionary, description) {
    if (dictionary !== descriptor.dictionary) {
        throw new Error(`${describeTag(descriptor.name, id, dictionary)} is in two dictionaries: ${descriptor.dictionary} and ${dictionary}`);
    }
    if (description && descriptor.description && description !== descriptor.description) {
        throw new Error(`${describeTag(descriptor.name, id, dictionary)} has two different descriptions`);
    }
    descriptor.ids.push(id);
    if (description) {
        descriptor.describedIds.push(id);
    }
    descriptor.description = descriptor.description || description;
}

function describeTag(name, id, dictionary) {
    return `Tag '${name}' (${getHex(id)} in the ${dictionary} dictionary)`;
}

function getHex(id) {
    return '0x' + id.toString(16).padStart(4, '0');
}

function getModuleText(output, descriptors, descriptionExports) {
    const imports = getImports(descriptors, descriptionExports);
    assertNamesAreDeclaredOnce(output, descriptors, imports);

    const lines = MPL_HEADER.concat(['', GENERATED_LINE, '']);
    const importLines = imports.map(getImportText);
    if (output.reader) {
        importLines.push(`import {${output.reader.binding}} from '${output.reader.file}';`);
    }
    if (importLines.length > 0) {
        lines.push(...importLines, '');
    }
    for (const descriptor of descriptors) {
        if (descriptor.isFirstOfDualName) {
            lines.push(DUAL_NAME_COMMENT);
        }
        lines.push(getDescriptorText(descriptor, output));
    }
    return lines.join('\n') + '\n';
}

// One import per description module, in DESCRIPTION_FILES order. Also sets
// each described descriptor's reference to its import.
function getImports(descriptors, descriptionExports) {
    const importsByFile = new Map();
    for (const descriptor of descriptors) {
        if (descriptor.description) {
            const source = descriptionExports.get(descriptor.description);
            if (!source) {
                throw new Error(`${describeTag(descriptor.name, descriptor.ids[0], descriptor.dictionary)} has a description that has no export in the description modules`);
            }
            const fileImport = getFileImport(importsByFile, source.file);
            if (!fileImport.named.includes(source.importName)) {
                fileImport.named.push(source.importName);
            }
            descriptor.reference = source.importName;
        }
    }
    return DESCRIPTION_FILES.filter((file) => importsByFile.has(file)).map((file) => {
        const fileImport = importsByFile.get(file);
        fileImport.named.sort();
        return fileImport;
    });
}

function getFileImport(importsByFile, file) {
    if (!importsByFile.has(file)) {
        importsByFile.set(file, {file, named: []});
    }
    return importsByFile.get(file);
}

function assertNamesAreDeclaredOnce(output, descriptors, imports) {
    const declarations = new Map();
    const declare = (name, origin) => {
        if (declarations.has(name)) {
            throw new Error(`${name} is declared twice in ${output.path}: by ${declarations.get(name)} and by ${origin}`);
        }
        declarations.set(name, origin);
    };
    for (const fileImport of imports) {
        for (const importName of fileImport.named) {
            declare(importName, `the import of ${importName} from ${fileImport.file}`);
        }
    }
    for (const descriptor of descriptors) {
        declare(descriptor.binding, describeTag(descriptor.name, descriptor.ids[0], descriptor.dictionary));
    }
}

function getImportText(fileImport) {
    const names = fileImport.named;
    if (names.length > 1) {
        return `import {\n${names.map((name) => '    ' + name).join(',\n')}\n} from '../../${fileImport.file}';`;
    }
    return `import {${names[0]}} from '../../${fileImport.file}';`;
}

// describedIds only when some id's dictionary entry has no description, so a
// reader built from the descriptors describes each id as its dictionary does.
function getDescriptorText(descriptor, output) {
    const fields = [
        `name: ${getStringLiteral(descriptor.name)}`,
        `ids: [${descriptor.ids.map(getHex).join(', ')}]`,
        `group: '${output.group}'`,
        `dictionary: '${descriptor.dictionary}'`
    ];
    if (descriptor.description) {
        fields.push(`description: ${descriptor.reference}`);
        if (descriptor.describedIds.length < descriptor.ids.length) {
            fields.push(`describedIds: [${descriptor.describedIds.map(getHex).join(', ')}]`);
        }
    }
    if (output.reader) {
        fields.push(`reader: ${output.reader.binding}`);
    }
    return `export const ${descriptor.binding} = {${fields.join(', ')}};`;
}

function getStringLiteral(text) {
    return '\'' + text.replace(/\\/g, '\\\\').replace(/'/g, '\\\'') + '\'';
}

function getTypesText(descriptors, group) {
    const lines = MPL_HEADER.concat(['', GENERATED_LINE, '', TYPES_IMPORT, '']);
    for (const descriptor of descriptors) {
        lines.push(`export declare const ${descriptor.binding}: TagDescriptor<'${group}', ${getStringLiteral(descriptor.name)}>;`);
    }
    return lines.join('\n') + '\n';
}
